# -*- coding: utf-8 -*-
"""Generate src/stub_esp32.h from esptool's stub_flasher json.

Usage:
    python tools/gen_stub_h.py [esp32.json] [out.h]

不写死路径。不传 json 时按下面顺序找:
    1. 环境变量 ESPTOOL_STUB_JSON
    2. $IDF_PYTHON_ENV_PATH 的 site-packages 里 esptool 自带的 stub_flasher/2/esp32.json
都用不上就报错, 让你显式传一个。
"""
import base64
import json
import os
import sys


def find_default_json():
    env = os.environ.get("ESPTOOL_STUB_JSON")
    if env and os.path.isfile(env):
        return env
    venv = os.environ.get("IDF_PYTHON_ENV_PATH")
    if not venv:
        return None
    base = os.path.join(venv, "Lib", "site-packages")
    for root, _dirs, files in os.walk(base):
        if "stub_flasher" in root and "esp32.json" in files:
            return os.path.join(root, "esp32.json")
    return None


def carray(name, buf):
    out = ["static const unsigned char %s[%d] = {" % (name, len(buf))]
    for i in range(0, len(buf), 12):
        out.append("    " + " ".join("0x%02x," % b for b in buf[i:i + 12]))
    out.append("};")
    return "\n".join(out)


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    root = os.path.dirname(here)
    src = sys.argv[1] if len(sys.argv) > 1 else find_default_json()
    if not src:
        print("找不到 esptool 的 esp32.json, 请显式传入:")
        print("  python tools/gen_stub_h.py <路径>/stub_flasher/2/esp32.json")
        print("或设置环境变量 ESPTOOL_STUB_JSON")
        return 2
    dst = sys.argv[2] if len(sys.argv) > 2 else os.path.join(root, "src", "stub_esp32.h")

    with open(src, "r", encoding="utf-8") as f:
        stub = json.load(f)

    text = base64.b64decode(stub["text"])
    data = base64.b64decode(stub["data"]) if stub.get("data") else b""

    lines = [
        "/* auto-generated by tools/gen_stub_h.py -- do not edit",
        " * ESP32 flasher stub from esptool (GPL-2.0-or-later), stub_flasher/2/esp32.json",
        " */",
        "#ifndef MF_STUB_ESP32_H",
        "#define MF_STUB_ESP32_H",
        "",
        "#define STUB_ENTRY      0x%08xu" % stub["entry"],
        "#define STUB_TEXT_ADDR  0x%08xu" % stub["text_start"],
        "#define STUB_DATA_ADDR  0x%08xu" % stub["data_start"],
        "#define STUB_BSS_ADDR   0x%08xu" % stub.get("bss_start", 0),
        "#define STUB_TEXT_LEN   %d" % len(text),
        "#define STUB_DATA_LEN   %d" % len(data),
        "",
        carray("stub_text", text),
        "",
        carray("stub_data", data),
        "",
        "#endif",
        "",
    ]
    with open(dst, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))

    print("stub: entry=0x%08x text=%d@0x%08x data=%d@0x%08x -> %s"
          % (stub["entry"], len(text), stub["text_start"], len(data), stub["data_start"], dst))


if __name__ == "__main__":
    sys.exit(main())
